"""Compare a local source proposal with read-only historical master layers."""
import argparse
from collections import Counter
import difflib
import hashlib
import json
from pathlib import Path


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--master', type=Path, default=Path('/Users/antonkrutov/Desktop/SiteForMods'))
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[1]
    glossary = project / 'glossary'
    old_path = args.master / 'data/games/omori/glossary.json'
    translations_path = old_path.with_name('glossary-translations.json')
    new_path = glossary / 'source-draft.json'
    old = json.loads(old_path.read_text())
    old = old if isinstance(old, list) else old['entries']
    new = json.loads(new_path.read_text())
    translations = json.loads(translations_path.read_text())
    assert len({e['id'] for e in old}) == len(old)
    assert len({e['id'] for e in new}) == len(new)
    old_ids = {e['id']: e for e in old}
    new_ids = {e['id']: e for e in new}
    changes = []
    for entry in old:
        if entry['id'] not in new_ids:
            continue
        replacement = new_ids[entry['id']]
        fields = {key: {'before': entry.get(key), 'after': replacement.get(key)}
                  for key in sorted(set(entry) | set(replacement))
                  if entry.get(key) != replacement.get(key)}
        if fields:
            changes.append({'id': entry['id'], 'fields': fields})
    meaning_ids = {e['id'] for e in changes if 'meaning' in e['fields']}
    term_ids = {e['id'] for e in changes if 'term' in e['fields']}
    report = {
        'schemaVersion': 1, 'game': 'omori',
        'scope': 'Local protected-source replacement proposal; no production query or mutation',
        'oldSourcePath': str(old_path), 'newSourcePath': str(new_path),
        'oldSourceRawSha256': digest(old_path), 'newSourceRawSha256': digest(new_path),
        'historicalTranslationsPath': str(translations_path),
        'historicalTranslationsRawSha256': digest(translations_path),
        'oldEntries': len(old), 'newEntries': len(new),
        'addedIds': [e['id'] for e in new if e['id'] not in old_ids],
        'removedIds': [e['id'] for e in old if e['id'] not in new_ids],
        'retainedIds': len(set(old_ids) & set(new_ids)), 'changedEntries': changes,
        'changedMeanings': len(meaning_ids), 'changedTerms': len(term_ids),
        'fieldChangeCounts': dict(Counter(key for e in changes for key in e['fields'])),
        'retainedRelativeOrderUnchanged': (
            [e['id'] for e in new if e['id'] in old_ids]
            == [e['id'] for e in old if e['id'] in new_ids]),
        'localeLayers': [],
        'limits': ['No locale is certified against the new meanings.',
                   'Local historical counts do not establish current production rows.',
                   'No proposal CLI fingerprint, production plan or backup is generated by this comparison.'],
    }
    for locale, rows in translations.items():
        report['localeLayers'].append({
            'locale': locale, 'historicalEntries': len(rows),
            'affectedExistingMeanings': len(set(rows) & meaning_ids),
            'affectedExistingTerms': len(set(rows) & term_ids),
            'newIdsWithoutTranslation': len(set(new_ids) - set(rows)),
            'orphanHistoricalIds': sorted(set(rows) - set(new_ids)),
            'readiness': 'needs-fresh-complete-translation-and-standard-review',
        })
    report_path = glossary / 'dependency-impact.json'
    if report_path.is_file():
        prior = json.loads(report_path.read_text())
        if prior.get('oldSourceRawSha256') == report['oldSourceRawSha256']:
            for key in ('historicalSourceCliFingerprint', 'masterCliCheck'):
                if key in prior:
                    report[key] = prior[key]
        if all(prior.get(key) == report[key] for key in (
                'oldSourceRawSha256', 'newSourceRawSha256', 'historicalTranslationsRawSha256')):
            if 'activeLocaleRetirementProposal' in prior:
                report['activeLocaleRetirementProposal'] = prior['activeLocaleRetirementProposal']
    report['proposalCliFingerprint'] = None
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    (glossary / 'source-replacement.diff').write_text(''.join(difflib.unified_diff(
        old_path.read_text().splitlines(keepends=True), new_path.read_text().splitlines(keepends=True),
        fromfile=str(old_path), tofile=str(new_path))))
    print(json.dumps({key: report[key] for key in (
        'oldEntries', 'newEntries', 'retainedIds', 'changedMeanings', 'changedTerms', 'fieldChangeCounts')}))


if __name__ == '__main__':
    main()
